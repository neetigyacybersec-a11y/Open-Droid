#!/usr/bin/env node
// ISSUE-104: generate the tool catalogue from the typed registry. The document
// is checked into the repository so reviewers can see safety classifications
// in a diff, and CI runs --check so it cannot drift from the code.
//
// Usage:
//   node scripts/tool-catalogue.mjs             # print Markdown to stdout
//   node scripts/tool-catalogue.mjs --write     # update docs/tool-catalogue.md
//   node scripts/tool-catalogue.mjs --check     # exit 1 if the document is stale
//   node scripts/tool-catalogue.mjs --safe      # print approval-free tools as JSON
//   node scripts/tool-catalogue.mjs --test-inventory
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

import {
  PLANNED_TOOLS,
  RISK_CLASSES,
  TOOL_CATEGORIES,
  TOOL_REGISTRY,
  baseImpact,
} from "../dist/registry.js";

const REPO = join(dirname(fileURLToPath(import.meta.url)), "..");
const DOC_PATH = join(REPO, "docs", "tool-catalogue.md");

function byName(left, right) {
  return left.name.localeCompare(right.name);
}

function approvalLabel(entry) {
  return entry.approval === "none" ? "none" : `${entry.approval} required`;
}

function renderMarkdown() {
  const lines = [
    "# MCP tool catalogue",
    "",
    "<!-- Generated by scripts/tool-catalogue.mjs from src/registry.ts. Do not edit by hand. -->",
    "",
    `The server registers **${TOOL_REGISTRY.length} tools**. Every entry is declared in`,
    "`src/registry.ts` with its schema, handler, risk class, approval requirement,",
    "path policy, provenance source and test references. Registration is a loop over",
    "that registry, so a tool cannot be added without those decisions.",
    "",
    "## Output content",
    "",
    "Every registered tool returns MCP text content. `adb_screenshot` and",
    "`compose_preview_render` additionally return inline PNG image content",
    "(`image/png`). No tool returns an MCP resource or embedded file: tools that",
    "persist files report the path and metadata as text. `tool_catalog` returns",
    "structured JSON encoded as text. Every other tool is text-only.",
    "",
    "## Risk summary",
    "",
    "| Risk class | Tools |",
    "|---|---:|",
  ];
  for (const risk of RISK_CLASSES) {
    lines.push(`| \`${risk}\` | ${TOOL_REGISTRY.filter((entry) => entry.risk === risk).length} |`);
  }
  lines.push("", "## Categories", "", "| Category | Tools |", "|---|---:|");
  for (const category of TOOL_CATEGORIES) {
    const count = TOOL_REGISTRY.filter((entry) => entry.category === category).length;
    if (count > 0) lines.push(`| \`${category}\` | ${count} |`);
  }

  for (const category of TOOL_CATEGORIES) {
    const entries = TOOL_REGISTRY.filter((entry) => entry.category === category).sort(byName);
    if (entries.length === 0) continue;
    lines.push("", `## ${category} (${entries.length})`, "");
    lines.push(
      "| Tool | Impact | Risk | Approval | Unattended | Source |",
      "|---|---|---|---|---|---|",
    );
    for (const entry of entries) {
      lines.push(
        `| \`${entry.name}\` | \`${baseImpact(entry)}\` | \`${entry.risk}\` | ${approvalLabel(entry)} | ${
          entry.unattended ? "yes" : "no"
        } | \`${entry.source}\` |`,
      );
    }
    lines.push("");
    for (const entry of entries) {
      lines.push(`### \`${entry.name}\``, "", entry.description, "");
      lines.push(`- Impact: \`${baseImpact(entry)}\``);
      if (entry.policyKey) {
        lines.push(`- Policy key: \`${entry.policyKey}\``);
      }
      if (entry.preconditions.length > 0) {
        lines.push(`- Preconditions: ${entry.preconditions.join("; ")}`);
      }
      if (entry.sideEffects.length > 0) {
        lines.push(
          `- Side effects: ${entry.sideEffects.map((effect) => `\`${effect}\``).join(", ")}`,
        );
      }
      if (entry.paths.length > 0) {
        lines.push(
          `- Path arguments: ${entry.paths
            .map((spec) => `\`${spec.field}\` (${spec.operation})`)
            .join(", ")}`,
        );
      }
      if (entry.alternative) {
        lines.push(`- Safer alternative: ${entry.alternative}`);
      }
      if (entry.timeoutMs) {
        lines.push(`- Default timeout: ${entry.timeoutMs} ms`);
      }
      if (entry.outputLimitBytes) {
        lines.push(`- Output limit: ${entry.outputLimitBytes} bytes`);
      }
      lines.push(`- Verification: ${entry.verification}`);
      lines.push(`- Tests: ${entry.tests.map((file) => `\`${file}\``).join(", ")}`);
      lines.push("");
    }
  }

  lines.push(
    "## Planned, not registered",
    "",
    "These names appear in design notes and feature requests but are **not",
    "registered**. Calling them fails; the table exists so documentation cannot",
    "be mistaken for a working capability.",
    "",
    "| Tool | Status | Summary | Tracking |",
    "|---|---|---|---|",
  );
  for (const tool of PLANNED_TOOLS) {
    const tracking = tool.tracking.map((issue) => `#${issue}`).join(", ");
    lines.push(`| \`${tool.name}\` | \`${tool.status}\` | ${tool.summary} | ${tracking} |`);
  }
  lines.push(
    "",
    "## Safe subset",
    "",
    "`tool_catalog` with `safeOnly: true` returns only tools with `approval: none`",
    "and `unattended: true`. That view is a discovery aid, not an OS sandbox: the",
    "workspace path policy and the execution boundary still apply to every call.",
    "",
    "## Test inventory",
    "",
    "`node scripts/tool-catalogue.mjs --test-inventory` prints a TSV row per tool",
    "with `referenced` or `registration-only` coverage and the test files it names.",
    "The inventory is generated from this registry so the #97 contract work can",
    "consume the same source rather than maintaining a second list.",
    "",
  );
  return lines.join("\n");
}

function renderSafe() {
  const safe = TOOL_REGISTRY.filter(
    (entry) => entry.approval === "none" && entry.unattended === true,
  ).sort(byName);
  return `${JSON.stringify(
    safe.map((entry) => ({
      name: entry.name,
      category: entry.category,
      risk: entry.risk,
      description: entry.description,
    })),
    null,
    2,
  )}\n`;
}

function renderTestInventory() {
  const rows = [...TOOL_REGISTRY].sort(byName).map((entry) => {
    const substantive = entry.tests.filter((file) => file !== "test/smoke.test.mjs");
    const coverage = substantive.length > 0 ? "referenced" : "registration-only";
    return `${entry.name}\t${coverage}\t${entry.tests.join(",")}`;
  });
  return `${rows.join("\n")}\n`;
}

const args = new Set(process.argv.slice(2));
if (args.has("--write")) {
  writeFileSync(DOC_PATH, renderMarkdown(), "utf8");
  console.log(`wrote ${DOC_PATH}`);
} else if (args.has("--check")) {
  let current;
  try {
    current = readFileSync(DOC_PATH, "utf8");
  } catch (error) {
    console.error(`missing ${DOC_PATH}: ${error instanceof Error ? error.message : error}`);
    process.exit(1);
  }
  const expected = renderMarkdown();
  if (current.replace(/\r\n/g, "\n") !== expected) {
    console.error(
      "docs/tool-catalogue.md is stale; run `node scripts/tool-catalogue.mjs --write`",
    );
    process.exit(1);
  }
  console.log(`tool catalogue is current (${TOOL_REGISTRY.length} tools)`);
} else if (args.has("--safe")) {
  process.stdout.write(renderSafe());
} else if (args.has("--test-inventory")) {
  process.stdout.write(renderTestInventory());
} else {
  process.stdout.write(`${renderMarkdown()}\n`);
}
